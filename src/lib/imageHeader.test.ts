import { expect, test } from "bun:test";
import { inspectImageBytes } from "./imageHeader";

function bytes(list: number[]): Uint8Array {
  return new Uint8Array(list);
}

test("reads JPEG dimensions from the SOF segment", () => {
  const header = bytes([
    0xff, 0xd8, // SOI
    0xff, 0xe0, 0x00, 0x10, // APP0, length 16
    ...new Array(14).fill(0x00), // APP0 payload
    0xff, 0xc0, 0x00, 0x0b, // SOF0, length 11
    0x08, 0x00, 0xc8, 0x01, 0x2c, // precision 8, height 200, width 300
    0x01, 0x01, 0x11, 0x00, // 1 component
    0xff, 0xd9, // EOI
  ]);
  expect(inspectImageBytes(header)).toEqual({ type: "jpeg", width: 300, height: 200 });
});

test("reads PNG dimensions from IHDR", () => {
  const header = bytes([
    0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, // signature
    0x00, 0x00, 0x00, 0x0d, // IHDR length 13
    0x49, 0x48, 0x44, 0x52, // "IHDR"
    0x00, 0x00, 0x00, 0x03, // width 3
    0x00, 0x00, 0x00, 0x02, // height 2
  ]);
  expect(inspectImageBytes(header)).toEqual({ type: "png", width: 3, height: 2 });
});

test("reads lossy WebP dimensions", () => {
  const header = bytes([
    0x52, 0x49, 0x46, 0x46, 0x1a, 0x00, 0x00, 0x00, // RIFF + size
    0x57, 0x45, 0x42, 0x50, // WEBP
    0x56, 0x50, 0x38, 0x20, 0x0e, 0x00, 0x00, 0x00, // VP8 chunk + size
    0x00, 0x00, 0x00, // frame tag
    0x9d, 0x01, 0x2a, // start code
    0x40, 0x00, 0x30, 0x00, // width 64, height 48
  ]);
  expect(inspectImageBytes(header)).toEqual({ type: "webp", width: 64, height: 48 });
});

test("reads lossless WebP dimensions", () => {
  const header = bytes([
    0x52, 0x49, 0x46, 0x46, 0x1a, 0x00, 0x00, 0x00,
    0x57, 0x45, 0x42, 0x50,
    0x56, 0x50, 0x38, 0x4c, 0x0e, 0x00, 0x00, 0x00, // VP8L chunk + size
    0x2f, 0x0f, 0xc0, 0x01, 0x00, // signature + packed 15/7 -> 16x8
  ]);
  expect(inspectImageBytes(header)).toEqual({ type: "webp", width: 16, height: 8 });
});

test("reads extended WebP dimensions", () => {
  const header = bytes([
    0x52, 0x49, 0x46, 0x46, 0x1a, 0x00, 0x00, 0x00,
    0x57, 0x45, 0x42, 0x50,
    0x56, 0x50, 0x38, 0x58, 0x0a, 0x00, 0x00, 0x00, // VP8X chunk + size 10
    0x00, 0x00, 0x00, 0x00, // flags + reserved
    0x63, 0x00, 0x00, // width - 1 = 99
    0x31, 0x00, 0x00, // height - 1 = 49
  ]);
  expect(inspectImageBytes(header)).toEqual({ type: "webp", width: 100, height: 50 });
});

test("rejects non-images and truncated headers", () => {
  expect(inspectImageBytes(bytes([]))).toBeNull();
  expect(inspectImageBytes(bytes([0x68, 0x65, 0x6c, 0x6c, 0x6f]))).toBeNull(); // "hello"
  expect(
    inspectImageBytes(bytes([0x47, 0x49, 0x46, 0x38, 0x39, 0x61])),
  ).toBeNull(); // GIF89a
  expect(
    inspectImageBytes(bytes([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])),
  ).toBeNull(); // PNG signature only
  expect(inspectImageBytes(bytes([0xff, 0xd8, 0xff, 0xd9]))).toBeNull(); // SOI + EOI, no SOF
  expect(
    inspectImageBytes(bytes([0x52, 0x49, 0x46, 0x46, 0x1a, 0x00, 0x00, 0x00])),
  ).toBeNull(); // RIFF only
});
